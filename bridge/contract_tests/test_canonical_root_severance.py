def _fixture(tmp_path, *, stale=False, nested=False, regular=False, backup=False,
             materializer="local"):
    prefix = tmp_path / "prefix"
    prefix_modules = prefix / "node_modules"
    package = prefix_modules / "package"
    package.mkdir(parents=True)
    (package / "owned.txt").write_text("owned", encoding="utf-8")
    boot = prefix_modules / "@deepseek-ai" / "dsh-app-boot" / "lib" / "index.js"
    boot.parent.mkdir(parents=True)
    boot.write_text("fixture boot module", encoding="utf-8")
    anchor = prefix_modules / "@deepseek-ai" / "dsh" / "package.json"
    anchor.parent.mkdir(parents=True)
    anchor.write_text('{"name":"@deepseek-ai/dsh"}', encoding="utf-8")
    home = tmp_path / "home"
    profile = home / "profiles" / "node_modules"
    profile.mkdir(parents=True)
    outside = tmp_path / "archive-target"
    outside.write_text("must not change", encoding="utf-8")
    link_parent = profile / "nested" if nested else profile
    link_parent.mkdir(exist_ok=True)
    target = outside if stale else package
    os.symlink(target, link_parent / "package-link")
    if regular:
        (profile / "unexpected.txt").write_text("do not mutate", encoding="utf-8")
    if backup:
        (profile.parent / "node_modules.u81-backup").mkdir()

    node = tmp_path / "fake-node"
    if materializer == "local":
        body = '''#!/usr/bin/env python3
import os
assert "--input-type=module" in os.sys.argv
assert "--eval" in os.sys.argv
assert "healProfilesModuleFallback" in os.sys.argv[-1]
assert os.path.isfile(os.environ["HARNESS_DSH_BOOT_MODULE"])
assert os.path.isfile(os.environ["HARNESS_DSH_INSTALL_ANCHOR"])
home = os.environ["HARNESS_DSH_PROFILE_HOME"]
prefix = os.environ["FIXTURE_PREFIX"]
tree = os.path.join(home, "profiles", "node_modules")
os.makedirs(os.path.join(tree, "nested"), exist_ok=True)
os.symlink(os.path.join(prefix, "node_modules", "package"), os.path.join(tree, "nested", "package-link"))
print("fixture healer")
'''
    elif materializer == "escape":
        body = '''#!/usr/bin/env python3
import os
home = os.environ["HARNESS_DSH_PROFILE_HOME"]
tree = os.path.join(home, "profiles", "node_modules")
os.makedirs(tree, exist_ok=True)
os.symlink(os.environ["FIXTURE_OUTSIDE"], os.path.join(tree, "escape"))
'''
    elif materializer == "timeout":
        body = "#!/usr/bin/env python3\nimport time\ntime.sleep(10)\n"
    else:
        body = "#!/usr/bin/env python3\nimport sys\nsys.exit(7)\n"
    node.write_text(body, encoding="utf-8")
    node.chmod(0o755)
    return prefix, home, profile, outside, node


def _repair(prefix, home, node, outside, *, timeout=None):
    env = dict(os.environ, FIXTURE_PREFIX=str(prefix), FIXTURE_OUTSIDE=str(outside))
    command = [sys.executable, REPAIR, "--prefix", str(prefix), "--home", str(home),
               "--node", str(node)]
    if timeout is not None:
        command += ["--timeout-seconds", str(timeout)]
    return subprocess.run(
        command,
        cwd=ROOT, env=env, capture_output=True, text=True, timeout=30,
    )


def test_deepseek_profile_repair_noops_for_clean_nested_local_links(tmp_path):
    prefix, home, profile, outside, node = _fixture(tmp_path, nested=True)
    before = os.readlink(profile / "nested" / "package-link")
    result = _repair(prefix, home, node, outside)
    assert result.returncode == 0, result.stderr + result.stdout
    assert "nothing to repair" in result.stdout
    assert os.readlink(profile / "nested" / "package-link") == before
    assert outside.read_text(encoding="utf-8") == "must not change"


def test_deepseek_profile_repair_rebuilds_external_and_dangling_links(tmp_path):
    prefix, home, profile, outside, node = _fixture(tmp_path, stale=True, nested=True)
    result = _repair(prefix, home, node, outside)
    assert result.returncode == 0, result.stderr + result.stdout
    rebuilt = profile / "nested" / "package-link"
    assert rebuilt.is_symlink()
    assert os.path.commonpath((os.path.realpath(rebuilt),
                               os.path.realpath(prefix / "node_modules"))) == \
        os.path.realpath(prefix / "node_modules")
    assert not (profile.parent / "node_modules.u81-backup").exists()
    assert outside.read_text(encoding="utf-8") == "must not change"

    dangling = tmp_path / "dangling"
    os.unlink(rebuilt)
    os.symlink(dangling, rebuilt)
    rerun = _repair(prefix, home, node, outside)
    assert rerun.returncode == 0, rerun.stderr + rerun.stdout
    assert os.path.realpath(profile / "nested" / "package-link").startswith(
        os.path.realpath(prefix / "node_modules") + os.sep
    )

    # A link can name this prefix textually but still be broken; it must rebuild too.
    os.unlink(profile / "nested" / "package-link")
    os.symlink(prefix / "node_modules" / "missing", profile / "nested" / "package-link")
    local_dangling = _repair(prefix, home, node, outside)
    assert local_dangling.returncode == 0, local_dangling.stderr + local_dangling.stdout
    assert os.path.exists(profile / "nested" / "package-link")


def test_deepseek_profile_repair_refuses_regular_entries_and_backup_collision(tmp_path):
    prefix, home, profile, outside, node = _fixture(tmp_path, stale=True, regular=True)
    regular = profile / "unexpected.txt"
    refused = _repair(prefix, home, node, outside)
    assert refused.returncode != 0
    assert regular.read_text(encoding="utf-8") == "do not mutate"
    assert (profile / "package-link").is_symlink()
    assert outside.read_text(encoding="utf-8") == "must not change"

    prefix, home, profile, outside, node = _fixture(tmp_path / "collision", stale=True,
                                                    backup=True)
    collision = _repair(prefix, home, node, outside)
    assert collision.returncode != 0
    assert "backup already exists" in collision.stderr
    assert (profile / "package-link").is_symlink()
    assert outside.read_text(encoding="utf-8") == "must not change"


def test_deepseek_profile_repair_rolls_back_failed_escaping_or_timed_out_materializer(tmp_path):
    for name, materializer in (("failed", "fail"), ("escaping", "escape"),
                               ("timed-out", "timeout")):
        prefix, home, profile, outside, node = _fixture(tmp_path / name, stale=True,
                                                        materializer=materializer)
        original = os.readlink(profile / "package-link")
        result = _repair(prefix, home, node, outside,
                         timeout=0.1 if materializer == "timeout" else None)
        assert result.returncode != 0
        assert os.readlink(profile / "package-link") == original, (
            "the old generated tree must return atomically after an unsuccessful rebuild"
        )
        assert not (profile.parent / "node_modules.u81-backup").exists()
        assert outside.read_text(encoding="utf-8") == "must not change"


