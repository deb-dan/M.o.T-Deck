def _venv_fixture(root, name, package, vendor_dir, *, fail_import=False,
                  binary=False, symlink=False, other_venv=None):
    """Small copied venv with a console script and an editable PEP 660 map."""
    venv = root / "data" / name
    bindir = venv / "bin"
    bindir.mkdir(parents=True)
    (venv / "pyvenv.cfg").write_text("home = /fixture/python", encoding="utf-8")
    old_root = "/archive root with spaces/harness"
    mapped_name = other_venv or name
    console = bindir / "fixture-console"
    console.write_text(f"#!{old_root}/data/{mapped_name}/bin/python\nprint('ok')\n",
                       encoding="utf-8")
    console.chmod(0o751)
    if binary:
        (bindir / "binary-launcher").write_bytes(b"\0not text")
    if symlink:
        os.symlink(console, bindir / "foreign-link")

    module = root / "vendor" / vendor_dir / package
    module.mkdir(parents=True)
    origin = module / "__init__.py"
    origin.write_text("# fixture\n", encoding="utf-8")
    module_stem = root / "vendor" / vendor_dir / "batch_runner.py"
    module_stem.write_text("# fixture module stem\n", encoding="utf-8")
    namespace = root / "vendor" / vendor_dir / "tools" / "wakewords"
    namespace.mkdir(parents=True)
    finder = (venv / "lib" / "python3.11" / "site-packages" /
              f"__editable___{vendor_dir}_finder.py")
    finder.parent.mkdir(parents=True)
    finder.write_text(
        f"MAPPING = {{'{package}': '{old_root}/vendor/{vendor_dir}/{package}', "
        f"'batch_runner': '{old_root}/vendor/{vendor_dir}/batch_runner'}}\n"
        f"NAMESPACES = {{'tools.wakewords': ['{old_root}/vendor/{vendor_dir}/tools/wakewords']}}\n",
        encoding="utf-8")

    python = bindir / "python"
    if fail_import:
        python.write_text("#!/usr/bin/env python3\nimport sys\nsys.exit(9)\n", encoding="utf-8")
    else:
        python.write_text(
            "#!/usr/bin/env python3\nimport os, sys\n"
            f"print({str(origin)!r})\n", encoding="utf-8")
    python.chmod(0o755)
    return venv, console, finder


def _repair_venvs(root):
    return subprocess.run([sys.executable, VENV_REPAIR, "--root", str(root)],
                          cwd=ROOT, capture_output=True, text=True, timeout=30)


def test_relocated_venv_repair_is_narrow_idempotent_and_preserves_mode(tmp_path):
    root = tmp_path / "canonical root with spaces"
    hermes, hermes_console, hermes_finder = _venv_fixture(
        root, "hermes-venv", "hermes_cli", "hermes")
    searx, searx_console, searx_finder = _venv_fixture(
        root, "searxng-venv", "searx", "searxng")
    ignored = root / "data" / "not-a-venv" / "bin"
    ignored.mkdir(parents=True)
    ignored_script = ignored / "old"
    ignored_script.write_text("#!/archive/data/hermes-venv/bin/python\n", encoding="utf-8")
    nested = root / "data" / "nested" / "bridge-venv"
    nested.mkdir(parents=True)
    (nested / "pyvenv.cfg").write_text("ignored", encoding="utf-8")
    bin_cache = hermes / "bin" / "__pycache__"
    bin_cache.mkdir()
    poisoned = bin_cache / "old-root.pyc"
    poisoned.write_text("/archive root with spaces/data/hermes-venv/bin/python\n",
                        encoding="utf-8")
    poisoned_before = poisoned.read_bytes()
    mode = stat.S_IMODE(hermes_console.stat().st_mode)

    result = _repair_venvs(root)
    assert result.returncode == 0, result.stderr + result.stdout
    assert "repaired 4" in result.stdout
    for venv, console, finder in ((hermes, hermes_console, hermes_finder),
                                  (searx, searx_console, searx_finder)):
        assert "/archive root with spaces" not in console.read_text(encoding="utf-8")
        assert str(venv) in console.read_text(encoding="utf-8")
        assert "/archive root with spaces" not in finder.read_text(encoding="utf-8")
        assert str(root / "vendor") in finder.read_text(encoding="utf-8")
    assert str(root / "vendor" / "hermes" / "batch_runner") in \
        hermes_finder.read_text(encoding="utf-8")
    assert stat.S_IMODE(hermes_console.stat().st_mode) == mode
    assert "/archive/data/hermes-venv" in ignored_script.read_text(encoding="utf-8")
    assert poisoned.read_bytes() == poisoned_before

    repaired_bytes = (hermes_console.read_bytes(), hermes_finder.read_bytes(),
                      searx_console.read_bytes(), searx_finder.read_bytes())
    rerun = _repair_venvs(root)
    assert rerun.returncode == 0, rerun.stderr + rerun.stdout
    assert "repaired 0" in rerun.stdout
    assert repaired_bytes == (hermes_console.read_bytes(), hermes_finder.read_bytes(),
                              searx_console.read_bytes(), searx_finder.read_bytes())


@pytest.mark.parametrize("kind", ("binary", "symlink", "other-venv", "fifo"))
def test_relocated_venv_repair_refuses_unsafe_or_ambiguous_console_inputs(tmp_path, kind):
    root = tmp_path / kind
    kwargs = {"binary": kind == "binary", "symlink": kind == "symlink",
              "other_venv": "bridge-venv" if kind == "other-venv" else None}
    _venv, console, finder = _venv_fixture(root, "hermes-venv", "hermes_cli", "hermes",
                                            **kwargs)
    if kind == "fifo":
        os.mkfifo(root / "data" / "hermes-venv" / "bin" / "not-a-console")
    before = (console.read_bytes(), finder.read_bytes())
    result = _repair_venvs(root)
    assert result.returncode != 0
    assert before == (console.read_bytes(), finder.read_bytes())


