def _prepare_config(root, config, main, binary):
    return subprocess.run(
        ["bash", SHIP, "--prepare-config-fixture", str(root), str(config),
         str(main), str(binary)],
        cwd=ROOT, capture_output=True, text=True, timeout=30,
    )


def test_ship_config_is_derived_atomically_and_recompile_tracks_it(tmp_path):
    root = tmp_path / "canonical root with spaces"
    root.mkdir()
    config = tmp_path / "Config.swift"
    main = tmp_path / "main.swift"
    binary = tmp_path / "Harness"
    main.write_text("main", encoding="utf-8")
    binary.write_text("binary", encoding="utf-8")
    os.utime(main, (10, 10))
    os.utime(binary, (20, 20))  # source is older: only config may request compile.

    config.write_text('let harnessRoot = "/stale/archive"\n', encoding="utf-8")
    changed = _prepare_config(root, config, main, binary)
    assert changed.returncode == 0, changed.stderr + changed.stdout
    assert "config_changed=1 would_recompile=1" in changed.stdout
    assert config.read_text(encoding="utf-8") == (
        "// generated by ship.sh — do not edit\n"
        f'let harnessRoot = "{root}"\n'
        "let fatBuild = true\n"
    )
    first_mtime = config.stat().st_mtime_ns
    # Model swiftc having consumed the generated config during the successful ship.
    binary_mtime = first_mtime + 2_000_000_000
    os.utime(binary, ns=(binary_mtime, binary_mtime))

    unchanged = _prepare_config(root, config, main, binary)
    assert unchanged.returncode == 0, unchanged.stderr + unchanged.stdout
    assert "config_changed=0 would_recompile=0" in unchanged.stdout
    assert config.stat().st_mtime_ns == first_mtime, (
        "an already-correct generated config must keep its mtime so an ordinary ship "
        "does not compile solely because this preparer ran"
    )

    # A prior ship may have generated the correct config before failing upstream of
    # swiftc. Its durable mtime must still make the next ship compile the stale binary.
    os.utime(config, ns=(binary_mtime + 2_000_000_000,
                         binary_mtime + 2_000_000_000))
    durable = _prepare_config(root, config, main, binary)
    assert durable.returncode == 0, durable.stderr + durable.stdout
    assert "config_changed=0 would_recompile=1" in durable.stdout


